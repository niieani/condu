import fs from "node:fs/promises";
import path from "node:path";
import { printUnifiedDiff } from "print-diff";
import { prompt } from "../../reporter/Prompt.js";
import { ConduReporter } from "../../reporter/ConduReporter.js";
import type { CollectionContext } from "./CollectedState.js";
import type {
  FileDestination,
  FileKind,
  PartialGlobalFileAttributes,
  WrittenFile,
} from "./fileTypes.js";

export class SymlinkTarget {
  readonly target: string;
  constructor(target: string) {
    this.target = target;
  }
  toString() {
    return `symlink:${this.target}`;
  }
}
function sameContent(a: string | SymlinkTarget, b: string | SymlinkTarget) {
  return typeof a === "string"
    ? typeof b === "string" && a === b
    : b instanceof SymlinkTarget && a.target === b.target;
}
function isMissing(error: unknown): boolean {
  return error instanceof Error && "code" in error && error.code === "ENOENT";
}
export async function write({
  targetPath,
  content,
  ignoreCache,
}: {
  targetPath: string;
  content: string | SymlinkTarget;
  ignoreCache?: boolean;
}): Promise<WrittenFile> {
  await fs.mkdir(path.dirname(targetPath), { recursive: true });
  if (typeof content === "string") await fs.writeFile(targetPath, content);
  else await fs.symlink(content.target, targetPath);
  const stat = await fs.lstat(targetPath);
  return {
    content,
    modifiedAt: stat.mtimeMs,
    size: stat.size,
    doNotCache: ignoreCache,
  };
}

/** Owns confirmed generated state, conflict decisions and filesystem effects. */
export class ManagedFileLifecycle {
  attributes: PartialGlobalFileAttributes = {};
  targetPackage: FileDestination["targetPackage"];
  relPath: string;
  get absPath() {
    return path.join(this.targetPackage.absPath, this.relPath);
  }
  hadChanges = false;
  managedByFeatures: CollectionContext[] = [];
  status: "pending" | "applied" | "skipped" | "needs-user-input" = "pending";
  manualConflictResolution?:
    | {
        printDiff: () => Promise<void>;
        promptUserInteractively: () => Promise<boolean>;
      }
    | undefined;
  manualReviewDetails?: string;
  lastApplyKind?: FileKind;
  protected neverCache = false;
  /** Last confirmed generated bytes, retained across skipped conflicts. */
  lastApply: WrittenFile | undefined;
  get shouldCache() {
    return Boolean(
      !this.neverCache && this.lastApply && !this.lastApply.doNotCache,
    );
  }
  constructor({ relPath, targetPackage }: FileDestination) {
    this.relPath = relPath;
    this.targetPackage = targetPackage;
  }
  async getFsFile(): Promise<WrittenFile | undefined> {
    try {
      const stat = await fs.lstat(this.absPath);
      const content = stat.isSymbolicLink()
        ? new SymlinkTarget(await fs.readlink(this.absPath))
        : await fs.readFile(this.absPath, "utf8");
      return { content, modifiedAt: stat.mtimeMs, size: stat.size };
    } catch (error) {
      if (isMissing(error)) return undefined;
      throw error;
    }
  }
  async getContentFromFileSystem(): Promise<string | undefined> {
    const file = await this.getFsFile();
    return typeof file?.content === "string" ? file.content : undefined;
  }
  async attemptWriteToFileSystem(
    newContent: string | SymlinkTarget,
    { overwriteWithoutAsking = false } = {},
  ): Promise<boolean> {
    return this.reconcile({ content: newContent, overwriteWithoutAsking });
  }
  async deleteFromFileSystem(): Promise<void> {
    if (this.lastApply) await this.reconcile({ content: undefined });
  }
  private async reconcile({
    content,
    overwriteWithoutAsking = false,
  }: {
    content: string | SymlinkTarget | undefined;
    overwriteWithoutAsking?: boolean;
  }): Promise<boolean> {
    this.manualReviewDetails = undefined;
    this.manualConflictResolution = undefined;
    this.hadChanges = false;
    const existing = await this.getFsFile();
    if (
      content !== undefined &&
      existing &&
      sameContent(existing.content, content)
    ) {
      this.lastApply = existing;
      this.status = "applied";
      return false;
    }
    if (content === undefined && !existing) {
      this.lastApply = undefined;
      this.status = "applied";
      return false;
    }
    const commit = async () => {
      // Unlink only after authorization, for either kind transition or removal.
      if (
        existing &&
        (content === undefined ||
          content instanceof SymlinkTarget ||
          existing.content instanceof SymlinkTarget)
      )
        await fs.unlink(this.absPath);
      this.lastApply =
        content === undefined
          ? undefined
          : await write({ targetPath: this.absPath, content });
      this.status = "applied";
      this.hadChanges = true;
      this.manualConflictResolution = undefined;
      this.manualReviewDetails = undefined;
      return true;
    };
    if (
      !existing ||
      overwriteWithoutAsking ||
      this.attributes.alwaysOverwrite ||
      (this.lastApply && sameContent(existing.content, this.lastApply.content))
    )
      return commit();
    this.status = "needs-user-input";
    this.manualReviewDetails =
      "Manual changes detected; review and re-run 'condu apply'.";
    const printDiff = async () => {
      ConduReporter.get().warn(`Manual changes present in ${this.relPath}`);
      printUnifiedDiff(
        existing.content.toString(),
        content?.toString() ?? "",
        process.stdout,
      );
    };
    this.manualConflictResolution = {
      printDiff,
      promptUserInteractively: async () => {
        await printDiff();
        const action = await prompt<"overwrite" | "skip">({
          message: `Manual review required: ${this.relPath}`,
          detail:
            content === undefined
              ? "This file is no longer generated. Delete its local modifications?"
              : "The file has local modifications. Choose how to proceed.",
          choices: [
            {
              key: "o",
              label:
                content === undefined
                  ? "Delete file"
                  : "Overwrite with generated version (condu)",
              value: "overwrite",
            },
            {
              key: "s",
              label: "Skip for now (keeps your current version)",
              value: "skip",
            },
          ],
          defaultKey: "s",
        });
        if (action === "overwrite") return commit();
        this.status = "skipped";
        this.manualConflictResolution = undefined;
        this.manualReviewDetails =
          "Kept your local changes; reconcile manually and rerun 'condu apply'.";
        process.exitCode = 1;
        return false;
      },
    };
    return false;
  }
}
